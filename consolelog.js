// console.log(argumento);
// Imprime algo no console. Pode ser texto, número, variável,
// resultado de contas, objetos, arrays e muito mais.

// ==================== STRINGS ====================

// String com aspas duplas
console.log("Olá");

// String com aspas simples
console.log('Olá');

// Utilizando aspas simples dentro de aspas duplas
console.log("João 'Marcelo'");

// Utilizando aspas duplas dentro de aspas simples
console.log('João "Marcelo"');

// Template String (crase)
// Permite utilizar aspas simples e duplas sem problemas
console.log(`"João" 'Marcelo'`);

// ==================== NÚMEROS ====================

// Número inteiro
console.log(10);

// Número decimal
console.log(30.5);

// Operações matemáticas
console.log(5 + 10);  // Soma
console.log(20 - 5);  // Subtração
console.log(4 * 5);   // Multiplicação
console.log(20 / 4);  // Divisão
console.log(10 % 3);  // Resto da divisão

// ==================== MÚLTIPLOS VALORES ====================

// Exibe vários valores na mesma linha
console.log(10, 30.5, 'João Marcelo');

